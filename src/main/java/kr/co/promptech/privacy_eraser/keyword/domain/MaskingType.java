package kr.co.promptech.privacy_eraser.keyword.domain;

/**
 * 비식별화 방식입니다.
 * <p>
 * 부분 마스킹은 <b>정보를 지우는 연산</b>이라 서로 다른 값이 같아질 수 있습니다. 그게 목적입니다.
 * 그래서 PK·UNIQUE 컬럼에는 쓸 수 없습니다. 고유성은 정반대로 서로 다른 값이 서로 달라야 하니까요.
 * <p>
 * 그런 컬럼에는 해시를 씁니다. 같은 값은 항상 같은 해시가, 다른 값은 다른 해시가 되어
 * 제약조건을 그대로 만들 수 있고 FK 도 따라옵니다.
 */
public enum MaskingType {

	/** `010-****-5678` 처럼 값의 일부를 가립니다. */
	PARTIAL,

	/** 값 전체를 되돌릴 수 없는 해시로 바꿉니다. 고유성이 유지됩니다. */
	HASH
}
